-- Kleidungsverwaltung Etappe 2: Positionen (Status je Artikel), Bestand mit optionaler Farbe,
-- Abbuchung bei Bestellung, Übernahme der offenen Bestellungen.
-- Einmalig im Supabase-Dashboard unter "SQL Editor" ausführen, BEVOR der neue Code hochgeladen wird.
-- Das Skript läuft komplett oder gar nicht (Transaktion). Ein zweites Ausführen schadet nicht:
-- Bestellungen, die schon Positionen haben, werden übersprungen.

begin;

-- ------------------------------------------------------------------
-- 1) Bestand: Farbe (leer = ohne Farbe, wie bisher)
-- ------------------------------------------------------------------
alter table public.clothing_stock add column if not exists color text not null default '';

-- Pro Artikel zuschaltbar: Bestand je Farbe führen (Standard: aus)
alter table public.clothing_items add column if not exists stock_by_color boolean not null default false;

-- ------------------------------------------------------------------
-- 2) Positionen: eine Zeile pro Stück
-- ------------------------------------------------------------------
create table if not exists public.clothing_order_positions (
    id               bigint generated by default as identity primary key,
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    order_id         bigint not null references public.clothing_orders(id) on delete cascade,
    item_index       integer not null,          -- Stelle im items-JSON der Bestellung (ab 0)
    member_id        bigint,
    member_name      text,
    clothing_item_id bigint,
    item_name        text,
    emoji            text,
    size             text,
    color            text,
    price            numeric(10,2) not null default 0,
    payment_method   text,
    status           text not null default 'bestellt'
                     check (status in ('bestellt', 'fehlt', 'abholbereit', 'ausgegeben', 'storniert')),
    billed           boolean not null default false,  -- "Berechnet" (unabhängig vom Status)
    billed_at        timestamptz,
    billing_id       bigint,
    ready_at         timestamptz,
    delivered_at     timestamptz,
    notes            text,
    stock_booked     boolean not null default false,  -- Bestand für dieses Stück abgebucht?
    stock_size       text,                            -- womit abgebucht wurde (für Rückbuchung)
    stock_color      text
);

create index if not exists clothing_order_positions_order_idx  on public.clothing_order_positions (order_id);
create index if not exists clothing_order_positions_member_idx on public.clothing_order_positions (member_id);
create index if not exists clothing_order_positions_status_idx on public.clothing_order_positions (status);

-- Die API greift wie bei den anderen Tabellen mit dem anon-Key zu.
alter table public.clothing_order_positions enable row level security;

drop policy if exists "clothing_order_positions_select" on public.clothing_order_positions;
drop policy if exists "clothing_order_positions_insert" on public.clothing_order_positions;
drop policy if exists "clothing_order_positions_update" on public.clothing_order_positions;
drop policy if exists "clothing_order_positions_delete" on public.clothing_order_positions;

create policy "clothing_order_positions_select" on public.clothing_order_positions
    for select to anon using (true);
create policy "clothing_order_positions_insert" on public.clothing_order_positions
    for insert to anon with check (true);
create policy "clothing_order_positions_update" on public.clothing_order_positions
    for update to anon using (true) with check (true);
create policy "clothing_order_positions_delete" on public.clothing_order_positions
    for delete to anon using (true);

-- ------------------------------------------------------------------
-- 3) Freimitglieder-Shirts: Bezug zum Artikel + Bestandsabbuchung bei "ausgeliefert"
-- ------------------------------------------------------------------
alter table public.free_shirts add column if not exists clothing_item_id bigint;
alter table public.free_shirts add column if not exists stock_booked boolean not null default false;
alter table public.free_shirts add column if not exists stock_size text;
alter table public.free_shirts add column if not exists stock_color text;

-- ------------------------------------------------------------------
-- 4) Funktionen zum Buchen des Bestands
-- ------------------------------------------------------------------

-- Bestand eines Artikels/Größe/Farbe um p_delta ändern (darf negativ werden).
-- Legt die Zeile an, wenn es sie noch nicht gibt. Gibt den neuen Bestand zurück.
create or replace function public.clothing_stock_adjust(
    p_item_id bigint, p_size text, p_color text, p_delta integer)
returns integer
language plpgsql security definer set search_path = public as $$
declare
    v_id  bigint;
    v_qty integer;
begin
    p_size  := coalesce(p_size, '');
    p_color := coalesce(p_color, '');
    -- verhindert, dass zwei gleichzeitige Buchungen sich gegenseitig überschreiben
    perform pg_advisory_xact_lock(hashtext('clothing_stock:' || p_item_id || ':' || p_size || ':' || p_color));

    select id into v_id
      from clothing_stock
     where clothing_item_id = p_item_id and size = p_size and coalesce(color, '') = p_color
     order by id
     limit 1
       for update;

    if v_id is null then
        insert into clothing_stock (clothing_item_id, size, color, quantity)
        values (p_item_id, p_size, p_color, p_delta)
        returning quantity into v_qty;
    else
        update clothing_stock
           set quantity = quantity + p_delta, updated_at = now()
         where id = v_id
        returning quantity into v_qty;
    end if;
    return v_qty;
end $$;

-- Farbe, unter der der Bestand geführt wird: nur bei Artikeln mit "Bestand nach Farbe", sonst leer.
create or replace function public.clothing_stock_color(p_item_id bigint, p_color text)
returns text
language sql stable security definer set search_path = public as $$
    select case when coalesce((select stock_by_color from clothing_items where id = p_item_id), false)
                then coalesce(p_color, '') else '' end;
$$;

-- Bestand für eine Position abbuchen (p_book = true) oder zurückbuchen (false).
-- Bucht nie doppelt. Gibt true zurück, wenn gebucht wurde.
create or replace function public.clothing_position_stock(p_position_id bigint, p_book boolean)
returns boolean
language plpgsql security definer set search_path = public as $$
declare
    r       clothing_order_positions%rowtype;
    v_color text;
begin
    select * into r from clothing_order_positions where id = p_position_id for update;
    if not found then return false; end if;

    if p_book and not r.stock_booked and r.clothing_item_id is not null then
        v_color := clothing_stock_color(r.clothing_item_id, r.color);
        perform clothing_stock_adjust(r.clothing_item_id, coalesce(r.size, ''), v_color, -1);
        update clothing_order_positions
           set stock_booked = true, stock_size = coalesce(r.size, ''), stock_color = v_color, updated_at = now()
         where id = r.id;
        return true;
    elsif not p_book and r.stock_booked then
        perform clothing_stock_adjust(r.clothing_item_id, r.stock_size, r.stock_color, 1);
        update clothing_order_positions
           set stock_booked = false, stock_size = null, stock_color = null, updated_at = now()
         where id = r.id;
        return true;
    end if;
    return false;
end $$;

-- Dasselbe für Freimitglieder-Shirts (bucht nur, wenn ein Artikel eingetragen ist).
create or replace function public.clothing_free_shirt_stock(p_shirt_id bigint, p_book boolean)
returns boolean
language plpgsql security definer set search_path = public as $$
declare
    r       free_shirts%rowtype;
    v_color text;
begin
    select * into r from free_shirts where id = p_shirt_id for update;
    if not found then return false; end if;

    if p_book and not r.stock_booked and r.clothing_item_id is not null then
        v_color := clothing_stock_color(r.clothing_item_id, r.color);
        perform clothing_stock_adjust(r.clothing_item_id, coalesce(r.size, ''), v_color, -1);
        update free_shirts
           set stock_booked = true, stock_size = coalesce(r.size, ''), stock_color = v_color
         where id = r.id;
        return true;
    elsif not p_book and r.stock_booked then
        perform clothing_stock_adjust(r.clothing_item_id, r.stock_size, r.stock_color, 1);
        update free_shirts
           set stock_booked = false, stock_size = null, stock_color = null
         where id = r.id;
        return true;
    end if;
    return false;
end $$;

-- Positionen für eine Bestellung aus dem items-JSON anlegen (ein Stück = eine Position)
-- und den Bestand abbuchen. Hat die Bestellung schon Positionen, passiert nichts.
create or replace function public.clothing_order_create_positions(
    p_order_id bigint,
    p_status   text    default 'bestellt',
    p_billed   boolean default false,
    p_book     boolean default true)
returns integer
language plpgsql security definer set search_path = public as $$
declare
    o       record;
    r       record;
    v_item  bigint;
    v_qty   integer;
    v_price numeric;
    v_pos   bigint;
    v_count integer := 0;
    i       integer;
begin
    select * into o from clothing_orders where id = p_order_id for update;
    if not found then return 0; end if;
    if exists (select 1 from clothing_order_positions where order_id = p_order_id) then return 0; end if;
    if o.items is null or jsonb_typeof(o.items::jsonb) <> 'array' then return 0; end if;

    for r in
        select value as it, (ordinality - 1)::integer as idx
          from jsonb_array_elements(o.items::jsonb) with ordinality
    loop
        v_item := case when (r.it->>'product_id') ~ '^[0-9]+$' then (r.it->>'product_id')::bigint end;
        v_qty  := case when (r.it->>'quantity') ~ '^[0-9]+$' then greatest((r.it->>'quantity')::integer, 1) else 1 end;
        v_price := case
            when (r.it->>'price') ~ '^-?[0-9]+(\.[0-9]+)?$' then (r.it->>'price')::numeric
            when (r.it->>'total') ~ '^-?[0-9]+(\.[0-9]+)?$' then (r.it->>'total')::numeric / v_qty
            else 0 end;

        for i in 1..v_qty loop
            insert into clothing_order_positions (
                order_id, item_index, member_id, member_name, clothing_item_id, item_name, emoji,
                size, color, price, payment_method, status, billed, billed_at, delivered_at, created_at)
            values (
                o.id, r.idx,
                case when o.member_id::text ~ '^[0-9]+$' then o.member_id::text::bigint end,
                o.member_name, v_item,
                coalesce(r.it->>'name', r.it->>'product_name'), r.it->>'emoji',
                nullif(r.it->>'size', ''), nullif(r.it->>'color', ''), v_price, o.payment_method,
                p_status, coalesce(p_billed, false), case when p_billed then now() end,
                case when p_status = 'ausgegeben' then coalesce(o.delivered_at, now()) end,
                coalesce(o.created_at, now()))
            returning id into v_pos;

            if p_book and p_status <> 'storniert' then
                perform clothing_position_stock(v_pos, true);
            end if;
            v_count := v_count + 1;
        end loop;
    end loop;
    return v_count;
end $$;

grant execute on function public.clothing_stock_adjust(bigint, text, text, integer) to anon;
grant execute on function public.clothing_stock_color(bigint, text) to anon;
grant execute on function public.clothing_position_stock(bigint, boolean) to anon;
grant execute on function public.clothing_free_shirt_stock(bigint, boolean) to anon;
grant execute on function public.clothing_order_create_positions(bigint, text, boolean, boolean) to anon;

-- ------------------------------------------------------------------
-- 5) Übernahme der bestehenden Bestellungen
--    pending/confirmed -> Bestellt, paid -> Bestellt + berechnet,
--    shipped -> Ausgegeben (nicht berechnet). completed/cancelled bleiben unverändert.
--    Der Bestand wird für alle übernommenen Stücke abgebucht.
-- ------------------------------------------------------------------
do $$
declare
    o record;
begin
    for o in
        select id, status, billed
          from public.clothing_orders
         where coalesce(status, 'pending') not in ('completed', 'cancelled')
         order by id
    loop
        perform public.clothing_order_create_positions(
            o.id,
            case when o.status = 'shipped' then 'ausgegeben' else 'bestellt' end,
            (coalesce(o.status, '') = 'paid' or coalesce(o.billed, false)),
            true);
    end loop;
end $$;

commit;

-- ------------------------------------------------------------------
-- Kontrolle: Anzahl Positionen je Status (wird nach dem Ausführen angezeigt)
-- ------------------------------------------------------------------
select status,
       count(*)                          as stueck,
       count(*) filter (where billed)    as davon_berechnet,
       count(*) filter (where stock_booked) as bestand_abgebucht
  from public.clothing_order_positions
 group by status
 order by status;
